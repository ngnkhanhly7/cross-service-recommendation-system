def _provenance_sidecar_path(data_path: str | Path) -> Path:
    return Path(str(data_path) + ".provenance.json")


def write_provenance_sidecar(
    data_path: str | Path, *, source: str, data_provenance: str
) -> Path:
    """Record where an interaction file came from, next to the file itself.

    Training/evaluation scripts read this back so every model artifact and report can
    carry an honest ``data_provenance`` tag instead of silently mixing synthetic and
    real-source metrics.
    """

    sidecar = _provenance_sidecar_path(data_path)
    sidecar.write_text(
        json.dumps({"source": source, "data_provenance": data_provenance}, indent=2),
        encoding="utf-8",
    )
    return sidecar


def read_provenance_sidecar(data_path: str | Path) -> dict[str, str]:
    sidecar = _provenance_sidecar_path(data_path)
    if not sidecar.exists():
        return {"source": "unknown", "data_provenance": "unknown"}
    return json.loads(sidecar.read_text(encoding="utf-8"))

